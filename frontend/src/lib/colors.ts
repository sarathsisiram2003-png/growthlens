// Sequential scale for opportunity score (viridis-like: reads on both dark and light basemaps).
const STOPS: [number, number, number][] = [
  [68, 1, 84],
  [59, 82, 139],
  [33, 145, 140],
  [94, 201, 98],
  [253, 231, 37],
];

export function scoreColor(t: number, alpha = 190): [number, number, number, number] {
  const x = Math.min(1, Math.max(0, t)) * (STOPS.length - 1);
  const i = Math.min(STOPS.length - 2, Math.floor(x));
  const f = x - i;
  const a = STOPS[i];
  const b = STOPS[i + 1];
  return [
    Math.round(a[0] + (b[0] - a[0]) * f),
    Math.round(a[1] + (b[1] - a[1]) * f),
    Math.round(a[2] + (b[2] - a[2]) * f),
    alpha,
  ];
}

export const LEGEND_GRADIENT = `linear-gradient(to right, ${STOPS.map(
  (s, i) => `rgb(${s.join(",")}) ${(i / (STOPS.length - 1)) * 100}%`,
).join(", ")})`;
